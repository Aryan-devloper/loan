from django import forms


class LoanPredictionForm(forms.Form):
    applicant_name = forms.CharField(label="Applicant name", required=False, max_length=120)
    Age = forms.IntegerField(min_value=18, max_value=90, initial=35)
    Gender = forms.ChoiceField(choices=[("Male", "Male"), ("Female", "Female")])
    Marital_Status = forms.ChoiceField(choices=[("Married", "Married"), ("Single", "Single")])
    Education = forms.ChoiceField(choices=[("High School", "High School"), ("Graduate", "Graduate"), ("Post Graduate", "Post Graduate")])
    City_Type = forms.ChoiceField(choices=[("Urban", "Urban"), ("Semi-Urban", "Semi-Urban"), ("Rural", "Rural")])
    Dependents = forms.IntegerField(min_value=0, max_value=10, initial=1)
    Applicant_Type = forms.ChoiceField(choices=[("Salaried", "Salaried"), ("Self-Employed", "Self-Employed"), ("Business", "Business")])
    Employment_Type = forms.ChoiceField(choices=[("Salaried", "Salaried"), ("Self-Employed", "Self-Employed"), ("Business", "Business")])
    Employment_Business_Age = forms.IntegerField(min_value=0, max_value=60, initial=5)
    Monthly_Income = forms.FloatField(min_value=0, initial=60000)
    Monthly_Expenses = forms.FloatField(min_value=0, initial=20000)
    Other_Income = forms.FloatField(min_value=0, initial=0)
    Existing_Loan = forms.ChoiceField(choices=[("No", "No"), ("Yes", "Yes")])
    Existing_Loan_Amount = forms.FloatField(min_value=0, initial=0)
    Monthly_EMI = forms.FloatField(min_value=0, initial=0)
    Bank_Balance = forms.FloatField(min_value=0, initial=250000)
    Savings_Amount = forms.FloatField(min_value=0, initial=250000)
    Credit_Score = forms.FloatField(min_value=300, max_value=900, initial=700)
    Credit_History_Length = forms.FloatField(min_value=0, initial=5)
    Late_Payments = forms.IntegerField(min_value=0, initial=0)
    House_Ownership = forms.ChoiceField(choices=[("Owned", "Owned"), ("Rented", "Rented"), ("Family", "Family")])
    Property_Value = forms.FloatField(min_value=0, initial=1000000)
    Vehicle_Ownership = forms.ChoiceField(choices=[("Yes", "Yes"), ("No", "No")])
    Collateral_Value = forms.FloatField(min_value=0, initial=500000)
    Loan_Type = forms.ChoiceField(choices=[("Home", "Home"), ("Business", "Business"), ("Personal", "Personal")])
    Loan_Amount = forms.FloatField(min_value=0, initial=500000)
    Loan_Tenure = forms.IntegerField(min_value=1, max_value=480, initial=120)
    Loan_Purpose = forms.ChoiceField(choices=[("Home Renovation", "Home Renovation"), ("Business", "Business"), ("Education", "Education"), ("Medical", "Medical"), ("Working Capital", "Working Capital")])
    Previous_Loan = forms.ChoiceField(choices=[("No", "No"), ("Yes", "Yes")])
